-- Village development project register.
-- Apply after 004_content_submission_admin.sql and the moderation migrations.
-- This migration adds a read-only public project register. It does not collect money.

create table if not exists public.village_projects (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 180),
  title text not null check (char_length(trim(title)) between 1 and 180),
  category text not null check (char_length(trim(category)) between 1 and 80),
  description text not null check (char_length(trim(description)) between 1 and 1200),
  details text check (details is null or char_length(details) <= 6000),
  location text check (location is null or char_length(location) <= 240),
  target_budget numeric(14, 2) not null default 0 check (target_budget >= 0),
  spent_amount numeric(14, 2) not null default 0 check (spent_amount >= 0),
  status text not null default 'planned' check (status in ('planned', 'in_progress', 'completed', 'on_hold')),
  start_date date,
  target_date date,
  published boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint village_projects_dates_check check (start_date is null or target_date is null or target_date >= start_date)
);

create index if not exists village_projects_published_created_idx on public.village_projects (published, created_at desc);
create index if not exists village_projects_status_idx on public.village_projects (status);

create or replace function public.set_village_projects_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists village_projects_set_updated_at on public.village_projects;
create trigger village_projects_set_updated_at before update on public.village_projects
for each row execute function public.set_village_projects_updated_at();

alter table public.village_projects enable row level security;

drop policy if exists "Public can read published village projects" on public.village_projects;
create policy "Public can read published village projects"
  on public.village_projects for select to anon, authenticated
  using (published = true);

drop policy if exists "Admins can manage village projects" on public.village_projects;
create policy "Admins can manage village projects"
  on public.village_projects for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

revoke all on public.village_projects from anon, authenticated;
grant select on public.village_projects to anon, authenticated;
grant insert, update, delete on public.village_projects to authenticated;

comment on table public.village_projects is 'Published village development projects and reported budgets. No payment or donation processing is performed by this table.';
comment on column public.village_projects.spent_amount is 'Administrator-reported expenditure; not a bank balance or independently verified amount.';
